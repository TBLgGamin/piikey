#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_preview_entries_of_a_known_type_have_a_blank() {
        assert!(blank("docProps/thumbnail.jpeg").is_some());
        assert!(blank("DocProps/Thumbnail.JPG").is_some());
        assert!(blank("docProps/thumbnail.png").is_some());
        assert!(blank("docProps/thumbnail.emf").is_some());
        assert!(blank("docProps/thumbnail.wmf").is_some());
        assert!(blank("Thumbnails/thumbnail.png").is_some());
        // A picture inside the document is content, not a preview.
        assert!(blank("word/media/thumbnail.png").is_none());
        assert!(blank("docProps/core.xml").is_none());
        assert!(blank("docProps/thumbnail").is_none());
        assert!(blank("docProps/thumbnail.tiff").is_none());
    }

    #[test]
    fn the_blank_pictures_decode_to_one_white_pixel() -> crate::Result<()> {
        for blank in [&JPEG[..], &PNG[..]] {
            assert_eq!(crate::ocr::first_pixel(blank)?, (1, 1, [255; 4]));
        }
        Ok(())
    }
}
