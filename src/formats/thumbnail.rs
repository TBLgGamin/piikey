//! The preview picture of a document's first page, which a rewritten package must not keep.
//!
//! Word, Excel, `PowerPoint` and `LibreOffice` can save a small picture of the first page in the
//! package (`docProps/thumbnail.jpeg`, `Thumbnails/thumbnail.png`), and Explorer shows it. A copy
//! with its text masked would still carry the unmasked page, so a rewrite swaps the picture for a
//! blank one of the same type. The entry keeps its name, so nothing that points at it (a
//! relationship, the manifest, the content types) dangles.

/// Names of the preview entries, without their extension.
const STEMS: [&str; 2] = ["docProps/thumbnail", "Thumbnails/thumbnail"];

/// A blank picture for the entry `name`, or `None` when `name` is not a preview entry or is of a
/// type that has no blank here.
pub(super) fn blank(name: &str) -> Option<&'static [u8]> {
    let (stem, extension) = name.rsplit_once('.')?;
    if !STEMS.iter().any(|known| known.eq_ignore_ascii_case(stem)) {
        return None;
    }
    match extension.to_ascii_lowercase().as_str() {
        "jpeg" | "jpg" => Some(&JPEG),
        "png" => Some(&PNG),
        "emf" => Some(&EMF),
        "wmf" => Some(&WMF),
        _ => None,
    }
}

